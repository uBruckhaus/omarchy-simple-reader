#!/usr/bin/env bash
# Regenerates reader/lock-*.txt: every file pip may install, with its sha256, for CPython 3.14
# on Linux x86_64. Direct pins are listed here; the current locks constrain everything else,
# so versions only move when a pin below changes. Needs uv. Review the diff before committing.
set -euo pipefail
cd "$(dirname -- "${BASH_SOURCE[0]}")/reader"
work=$(mktemp -d); trap 'rm -rf "$work"' EXIT
opts=(--generate-hashes --python-version 3.14 --python-platform x86_64-manylinux_2_39 --no-header --no-annotate -q)
lock() {  # name, extra uv options..., -- pins...
  local name=$1; shift; local extra=(); while [[ $1 != -- ]]; do extra+=("$1"); shift; done; shift
  printf '%s\n' "$@" > "$work/$name.in"
  [[ -f lock-$name.txt ]] && extra+=(-c "lock-$name.txt")
  uv pip compile "$work/$name.in" "${opts[@]}" "${extra[@]}" -o "$work/$name.txt"
  { echo "# Generated by update-locks.sh: exact files (sha256) for CPython 3.14, Linux x86_64. Do not edit."; cat "$work/$name.txt"; } > "lock-$name.txt"
}
lock base --only-binary :all: -- $(grep -v '^#' ../requirements.txt)
lock build --only-binary :all: -- setuptools wheel Cython
lock nllb --only-binary :all: -c lock-base.txt -- ctranslate2==4.8.2 tokenizers==0.23.3
lock japanese --only-binary :all: --no-binary mojimoji --no-binary unidic-lite -c lock-base.txt -- \
  'misaki[ja]==0.7.4' fugashi==1.5.2 unidic-lite==1.0.8 jaconv==0.5.0 mojimoji==0.0.13
lock piper --only-binary :all: -- piper-tts==1.8.0
